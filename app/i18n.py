def request_language(request: Request) -> tuple[str, bool]:
    """Sprache aus expliziter Wahl, Cookie oder Accept-Language bestimmen."""
    selected = request.query_params.get("lang", "").lower()
    if selected in UI_TRANSLATIONS:
        return selected, True
    stored = request.cookies.get("kiwiki_language", "").lower()
    if stored in UI_TRANSLATIONS:
        return stored, False
    accepted = request.headers.get("Accept-Language", "").lower()
    return ("en" if accepted.startswith("en") else "de"), False


def template_language_context(request: Request) -> dict[str, object]:
    """Gemeinsamer Jinja-Kontext fuer Seiten und HTMX-Fragmente."""
    language, _explicit = request_language(request)
    return {"lang": language, "t": UI_TRANSLATIONS[language]}
